const { getDb } = require('./db');

function statements(dialect) {
  const id = dialect === 'pg'
    ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
    : 'INTEGER PRIMARY KEY AUTOINCREMENT';
  const money = dialect === 'pg' ? 'BIGINT' : 'INTEGER';
  const qty = dialect === 'pg' ? 'DOUBLE PRECISION' : 'REAL';
  const rate = dialect === 'pg' ? 'DOUBLE PRECISION' : 'REAL';
  return [
    `CREATE TABLE IF NOT EXISTS users (
      id ${id}, username TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL, name TEXT NOT NULL,
      role TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS companies (
      id ${id}, name TEXT NOT NULL, commercial_name TEXT, ruc TEXT NOT NULL, address TEXT,
      city TEXT, province TEXT, phone TEXT, email TEXT, obligado INTEGER NOT NULL DEFAULT 1,
      regimen TEXT NOT NULL DEFAULT 'GENERAL', agente_retencion INTEGER NOT NULL DEFAULT 0,
      resolucion_agente TEXT, tipo_contribuyente TEXT, is_demo INTEGER NOT NULL DEFAULT 0,
      establecimiento TEXT NOT NULL DEFAULT '001', punto_emision TEXT NOT NULL DEFAULT '001',
      ambiente_sri TEXT NOT NULL DEFAULT '1', created_at TEXT NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS user_companies (
      user_id INTEGER NOT NULL REFERENCES users(id), company_id INTEGER NOT NULL REFERENCES companies(id),
      PRIMARY KEY (user_id, company_id))`,
    `CREATE TABLE IF NOT EXISTS accounts (
      id ${id}, company_id INTEGER NOT NULL REFERENCES companies(id), parent_id INTEGER REFERENCES accounts(id),
      code TEXT NOT NULL, name TEXT NOT NULL, type TEXT NOT NULL, nature TEXT NOT NULL,
      is_movement INTEGER NOT NULL DEFAULT 0, active INTEGER NOT NULL DEFAULT 1,
      UNIQUE (company_id, code))`,
    `CREATE TABLE IF NOT EXISTS settings (
      company_id INTEGER NOT NULL REFERENCES companies(id), skey TEXT NOT NULL, svalue TEXT NOT NULL,
      PRIMARY KEY (company_id, skey))`,
    `CREATE TABLE IF NOT EXISTS sequences (
      company_id INTEGER NOT NULL REFERENCES companies(id), doc_type TEXT NOT NULL, last_no INTEGER NOT NULL,
      PRIMARY KEY (company_id, doc_type))`,
    `CREATE TABLE IF NOT EXISTS parties (
      id ${id}, company_id INTEGER NOT NULL REFERENCES companies(id), kind TEXT NOT NULL,
      id_type TEXT NOT NULL, identification TEXT NOT NULL, name TEXT NOT NULL, commercial_name TEXT,
      person_type TEXT, email TEXT, phone TEXT, address TEXT, related_party INTEGER NOT NULL DEFAULT 0,
      is_partner INTEGER NOT NULL DEFAULT 0, blocked INTEGER NOT NULL DEFAULT 0, active INTEGER NOT NULL DEFAULT 1,
      credit_days INTEGER NOT NULL DEFAULT 0, credit_limit_cents ${money} NOT NULL DEFAULT 0,
      also_client INTEGER NOT NULL DEFAULT 0, position TEXT, department TEXT, hire_date TEXT,
      salary_cents ${money} NOT NULL DEFAULT 0, reserve_fund INTEGER NOT NULL DEFAULT 0,
      thirteenth_monthly INTEGER NOT NULL DEFAULT 1, fourteenth_monthly INTEGER NOT NULL DEFAULT 1,
      UNIQUE (company_id, kind, identification))`,
    `CREATE TABLE IF NOT EXISTS products (
      id ${id}, company_id INTEGER NOT NULL REFERENCES companies(id), code TEXT NOT NULL, name TEXT NOT NULL,
      kind TEXT NOT NULL, unit TEXT NOT NULL DEFAULT 'UND', inventoriable INTEGER NOT NULL DEFAULT 0,
      iva_rate INTEGER NOT NULL DEFAULT 15, ice_rate ${rate} NOT NULL DEFAULT 0,
      price_cents ${money} NOT NULL DEFAULT 0, stock_qty ${qty} NOT NULL DEFAULT 0,
      stock_value_cents ${money} NOT NULL DEFAULT 0, avg_cost_cents ${money} NOT NULL DEFAULT 0,
      active INTEGER NOT NULL DEFAULT 1, UNIQUE (company_id, code))`,
    `CREATE TABLE IF NOT EXISTS journal_entries (
      id ${id}, company_id INTEGER NOT NULL REFERENCES companies(id), doc_date TEXT NOT NULL,
      doc_number TEXT NOT NULL, description TEXT NOT NULL, source TEXT NOT NULL, source_id INTEGER,
      status TEXT NOT NULL, created_by INTEGER, created_at TEXT NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS journal_lines (
      id ${id}, entry_id INTEGER NOT NULL REFERENCES journal_entries(id), account_id INTEGER NOT NULL REFERENCES accounts(id),
      debit_cents ${money} NOT NULL DEFAULT 0, credit_cents ${money} NOT NULL DEFAULT 0,
      description TEXT, party_id INTEGER)`,
    `CREATE TABLE IF NOT EXISTS documents (
      id ${id}, company_id INTEGER NOT NULL REFERENCES companies(id), doc_type TEXT NOT NULL,
      doc_number TEXT NOT NULL, doc_date TEXT NOT NULL, due_date TEXT, party_id INTEGER REFERENCES parties(id),
      party_name TEXT, party_ident TEXT, status TEXT NOT NULL, payment_method TEXT, sri_pay_code TEXT,
      term_days INTEGER NOT NULL DEFAULT 0, subtotal_cents ${money} NOT NULL DEFAULT 0,
      discount_cents ${money} NOT NULL DEFAULT 0, base15_cents ${money} NOT NULL DEFAULT 0,
      base0_cents ${money} NOT NULL DEFAULT 0, ice_cents ${money} NOT NULL DEFAULT 0,
      iva_cents ${money} NOT NULL DEFAULT 0, total_cents ${money} NOT NULL DEFAULT 0,
      ret_iva_cents ${money} NOT NULL DEFAULT 0, ret_renta_cents ${money} NOT NULL DEFAULT 0,
      cheque_number TEXT, cheque_bank TEXT, cheque_date TEXT, cheque_postdated INTEGER NOT NULL DEFAULT 0,
      notes TEXT, related_document_id INTEGER REFERENCES documents(id), sustento TEXT DEFAULT '01',
      establecimiento TEXT, punto_emision TEXT, journal_entry_id INTEGER REFERENCES journal_entries(id),
      sri_status TEXT NOT NULL DEFAULT 'NO_APLICA', created_by INTEGER, created_at TEXT NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS document_lines (
      id ${id}, document_id INTEGER NOT NULL REFERENCES documents(id), product_id INTEGER REFERENCES products(id),
      description TEXT NOT NULL, qty ${qty} NOT NULL, unit_price_cents ${money} NOT NULL,
      discount_cents ${money} NOT NULL DEFAULT 0, iva_rate INTEGER NOT NULL, ice_rate ${rate} NOT NULL DEFAULT 0,
      base_cents ${money} NOT NULL, ice_cents ${money} NOT NULL DEFAULT 0, iva_cents ${money} NOT NULL DEFAULT 0,
      total_cents ${money} NOT NULL, cost_cents ${money} NOT NULL DEFAULT 0, kind TEXT NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS retention_lines (
      id ${id}, document_id INTEGER NOT NULL REFERENCES documents(id), tax TEXT NOT NULL, code TEXT NOT NULL,
      base_cents ${money} NOT NULL, rate ${rate} NOT NULL, amount_cents ${money} NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS open_items (
      id ${id}, company_id INTEGER NOT NULL REFERENCES companies(id), side TEXT NOT NULL, kind TEXT NOT NULL,
      party_id INTEGER NOT NULL REFERENCES parties(id), document_id INTEGER REFERENCES documents(id),
      doc_date TEXT NOT NULL, due_date TEXT, doc_number TEXT NOT NULL, description TEXT,
      original_cents ${money} NOT NULL, balance_cents ${money} NOT NULL, status TEXT NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS bank_accounts (
      id ${id}, company_id INTEGER NOT NULL REFERENCES companies(id), name TEXT NOT NULL, bank_name TEXT,
      account_number TEXT, ledger_account_id INTEGER NOT NULL REFERENCES accounts(id),
      opening_balance_cents ${money} NOT NULL DEFAULT 0, opening_date TEXT, active INTEGER NOT NULL DEFAULT 1)`,
    `CREATE TABLE IF NOT EXISTS settlements (
      id ${id}, company_id INTEGER NOT NULL REFERENCES companies(id), side TEXT NOT NULL, kind TEXT NOT NULL,
      doc_number TEXT NOT NULL, doc_date TEXT NOT NULL, party_id INTEGER REFERENCES parties(id),
      method TEXT, bank_account_id INTEGER REFERENCES bank_accounts(id), total_cents ${money} NOT NULL,
      unapplied_cents ${money} NOT NULL DEFAULT 0, advance_item_id INTEGER, journal_entry_id INTEGER REFERENCES journal_entries(id),
      notes TEXT, status TEXT NOT NULL, created_by INTEGER, created_at TEXT NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS settlement_lines (
      id ${id}, settlement_id INTEGER NOT NULL REFERENCES settlements(id),
      target_item_id INTEGER NOT NULL REFERENCES open_items(id), amount_cents ${money} NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS bank_movements (
      id ${id}, company_id INTEGER NOT NULL REFERENCES companies(id), bank_account_id INTEGER NOT NULL REFERENCES bank_accounts(id),
      doc_date TEXT NOT NULL, kind TEXT NOT NULL, doc_number TEXT, description TEXT,
      debit_cents ${money} NOT NULL DEFAULT 0, credit_cents ${money} NOT NULL DEFAULT 0,
      status TEXT NOT NULL, reconciled INTEGER NOT NULL DEFAULT 0, reconcile_date TEXT,
      postdated INTEGER NOT NULL DEFAULT 0, counterpart_bank_id INTEGER, journal_entry_id INTEGER,
      posts_journal INTEGER NOT NULL DEFAULT 0, source TEXT, source_id INTEGER, created_at TEXT NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS warehouse_docs (
      id ${id}, company_id INTEGER NOT NULL REFERENCES companies(id), doc_type TEXT NOT NULL,
      doc_number TEXT NOT NULL, doc_date TEXT NOT NULL, notes TEXT, from_warehouse TEXT, to_warehouse TEXT,
      journal_entry_id INTEGER, created_at TEXT NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS inventory_moves (
      id ${id}, company_id INTEGER NOT NULL REFERENCES companies(id), product_id INTEGER NOT NULL REFERENCES products(id),
      doc_date TEXT NOT NULL, kind TEXT NOT NULL, doc_number TEXT, document_id INTEGER, warehouse_doc_id INTEGER,
      description TEXT, qty_in ${qty} NOT NULL DEFAULT 0, qty_out ${qty} NOT NULL DEFAULT 0,
      total_cost_cents ${money} NOT NULL DEFAULT 0, balance_qty ${qty} NOT NULL DEFAULT 0,
      balance_value_cents ${money} NOT NULL DEFAULT 0, avg_cost_cents ${money} NOT NULL DEFAULT 0)`,
    `CREATE TABLE IF NOT EXISTS payroll_runs (
      id ${id}, company_id INTEGER NOT NULL REFERENCES companies(id), year INTEGER NOT NULL, month INTEGER NOT NULL,
      status TEXT NOT NULL, journal_entry_id INTEGER, total_net_cents ${money} NOT NULL DEFAULT 0,
      created_at TEXT NOT NULL, UNIQUE (company_id, year, month))`,
    `CREATE TABLE IF NOT EXISTS payroll_lines (
      id ${id}, run_id INTEGER NOT NULL REFERENCES payroll_runs(id), employee_id INTEGER NOT NULL REFERENCES parties(id),
      salary_cents ${money} NOT NULL, hours50 ${rate} NOT NULL DEFAULT 0, hours100 ${rate} NOT NULL DEFAULT 0,
      overtime_cents ${money} NOT NULL, bonuses_cents ${money} NOT NULL, thirteenth_cents ${money} NOT NULL,
      fourteenth_cents ${money} NOT NULL, reserve_cents ${money} NOT NULL, iess_personal_cents ${money} NOT NULL,
      iess_employer_cents ${money} NOT NULL, deductions_cents ${money} NOT NULL, net_cents ${money} NOT NULL,
      thirteenth_monthly INTEGER NOT NULL, fourteenth_monthly INTEGER NOT NULL, reserve_monthly INTEGER NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS year_closes (
      company_id INTEGER NOT NULL REFERENCES companies(id), year INTEGER NOT NULL,
      entry_id INTEGER, closed_at TEXT NOT NULL, PRIMARY KEY (company_id, year))`,
    `CREATE INDEX IF NOT EXISTS idx_docs_company ON documents(company_id, doc_type, doc_date)`,
    `CREATE INDEX IF NOT EXISTS idx_je_company ON journal_entries(company_id, doc_date)`,
    `CREATE INDEX IF NOT EXISTS idx_jl_entry ON journal_lines(entry_id)`,
    `CREATE INDEX IF NOT EXISTS idx_oi ON open_items(company_id, side, status)`,
    `CREATE INDEX IF NOT EXISTS idx_moves ON inventory_moves(company_id, product_id, doc_date)`,
  ];
}

async function ensureSchema() {
  const db = getDb();
  for (const sql of statements(db.dialect)) await db.exec(sql);
}

module.exports = { ensureSchema, statements };
